def build_system_prompt(watched_titles: list[str]) -> str:
    if watched_titles:
        watched_block = (
            "Пользователь уже смотрел: " + ", ".join(watched_titles) + ". "
            "Не советуй эти фильмы снова."
        )
    else:
        watched_block = "Пользователь пока не отметил ни одного просмотренного фильма."

    return (
        "Ты — помощник по подбору фильмов в Telegram-боте. Общайся кратко и по-русски. "
        "Если настроение или запрос пользователя ещё не понятны — задай один уточняющий вопрос, "
        "не вызывая инструмент. "
        "Как только готов предложить конкретные фильмы — вызови инструмент propose_movies "
        "с их названиями (оригинальными, чтобы легче искалось в базе фильмов), годом выхода "
        "и коротким объяснением, почему каждый подходит запросу. "
        "Не выдумывай подробности сюжета, в которых не уверен. "
        f"{watched_block}"
    )
